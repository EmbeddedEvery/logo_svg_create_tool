import type { LNode, Scene } from './types'

const esc = (s: string) =>
  s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')

export const num = (n: number) => {
  const r = Math.round(n * 1000) / 1000
  return Object.is(r, -0) ? 0 : r
}

function paint(n: LNode): string {
  const a: string[] = []
  if (n.fill && n.fill !== 'none') {
    a.push(`fill="${esc(n.fill)}"`)
    if (n.fillOpacity !== 1) a.push(`fill-opacity="${num(n.fillOpacity)}"`)
  } else {
    a.push('fill="none"')
  }
  if (n.stroke && n.stroke !== 'none' && n.strokeWidth > 0) {
    a.push(`stroke="${esc(n.stroke)}"`)
    a.push(`stroke-width="${num(n.strokeWidth)}"`)
    if (n.strokeOpacity !== 1) a.push(`stroke-opacity="${num(n.strokeOpacity)}"`)
    a.push('stroke-linecap="round"')
    a.push('stroke-linejoin="round"')
  }
  return a.join(' ')
}

function body(n: LNode): string {
  switch (n.type) {
    case 'rect': {
      const r = Math.min(n.radius, Math.min(n.width, n.height) / 2)
      return `<rect width="${num(n.width)}" height="${num(n.height)}"${r > 0 ? ` rx="${num(r)}"` : ''}/>`
    }
    case 'ellipse':
      return `<ellipse cx="${num(n.rx)}" cy="${num(n.ry)}" rx="${num(n.rx)}" ry="${num(n.ry)}"/>`
    case 'path':
      return `<path d="${esc(n.d)}"/>`
    case 'text': {
      const lh = n.fontSize * 1.18
      const lines = n.text.split('\n')
      const anchor = n.align === 'center' ? 'middle' : n.align === 'right' ? 'end' : 'start'
      const tspans = lines
        .map(
          (line, i) =>
            `<tspan x="0" y="${num(n.fontSize * 0.8 + i * lh)}">${esc(line)}</tspan>`,
        )
        .join('')
      return (
        `<text font-family="${esc(n.fontFamily)}" font-size="${num(n.fontSize)}"` +
        ` font-weight="${n.fontWeight}" font-style="${n.fontStyle}"` +
        ` text-anchor="${anchor}"` +
        (n.letterSpacing ? ` letter-spacing="${num(n.letterSpacing)}"` : '') +
        ` xml:space="preserve">${tspans}</text>`
      )
    }
  }
}

export function nodeToSvg(n: LNode): string {
  if (!n.visible) return ''
  const t = [`translate(${num(n.x)} ${num(n.y)})`]
  if (n.rotation) t.push(`rotate(${num(n.rotation)})`)
  if (n.scaleX !== 1 || n.scaleY !== 1) t.push(`scale(${num(n.scaleX)} ${num(n.scaleY)})`)
  const attrs = [`transform="${t.join(' ')}"`, paint(n)]
  if (n.opacity !== 1) attrs.push(`opacity="${num(n.opacity)}"`)
  return `<g data-id="${n.id}" ${attrs.join(' ')}>${body(n)}</g>`
}

export function nodesToSvg(nodes: LNode[]): string {
  return nodes.map(nodeToSvg).join('')
}

/** The artboard outline as an SVG element. `fill` omitted leaves the attribute off. */
export function artboardElement(scene: Scene, fill?: string): string {
  const fillAttr = fill === undefined ? '' : ` fill="${esc(fill)}"`
  if (scene.shape === 'ellipse') {
    const rx = num(scene.width / 2)
    const ry = num(scene.height / 2)
    return `<ellipse cx="${rx}" cy="${ry}" rx="${rx}" ry="${ry}"${fillAttr}/>`
  }
  const r =
    scene.shape === 'round'
      ? Math.min(scene.radius, Math.min(scene.width, scene.height) / 2)
      : 0
  return (
    `<rect x="0" y="0" width="${num(scene.width)}" height="${num(scene.height)}"` +
    `${r > 0 ? ` rx="${num(r)}"` : ''}${fillAttr}/>`
  )
}

export function serializeScene(
  scene: Scene,
  opts: { transparent?: boolean } = {},
): string {
  const w = num(scene.width)
  const h = num(scene.height)
  const clipped = scene.shape !== 'rect'
  const defs = clipped
    ? `<defs><clipPath id="artboard-clip">${artboardElement(scene)}</clipPath></defs>`
    : ''
  const bg =
    scene.background && !opts.transparent ? artboardElement(scene, scene.background) : ''
  const body = [bg, nodesToSvg(scene.nodes)].filter(Boolean).join('\n')
  const inner = clipped ? `<g clip-path="url(#artboard-clip)">\n${body}\n</g>` : body

  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">`,
    '<!-- Generated by Logo Studio -->',
    defs,
    inner,
    '</svg>',
    '',
  ]
    .filter((line) => line !== '')
    .join('\n')
}
